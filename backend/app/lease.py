"""One process owns a metadata/vault directory. Lock released by the OS on crash."""
import os

class InstanceLease:
    def __init__(self,folder):self.folder=folder;self.file=None
    def __enter__(self):
        self.folder.mkdir(parents=True,exist_ok=True)
        self.file=open(self.folder/'instance.lock','a+b')
        self.file.seek(0);self.file.write(b'0');self.file.flush();self.file.seek(0)
        try:
            if os.name=='nt':
                import msvcrt
                msvcrt.locking(self.file.fileno(),msvcrt.LK_NBLCK,1)
            else:
                import fcntl
                fcntl.flock(self.file.fileno(),fcntl.LOCK_EX|fcntl.LOCK_NB)
        except OSError:
            self.file.close();raise RuntimeError('This data directory is in use. Run one app process; stop it before offline backup or restore.') from None
        return self
    def __exit__(self,*args):
        if self.file:
            self.file.seek(0)
            if os.name=='nt':
                import msvcrt
                msvcrt.locking(self.file.fileno(),msvcrt.LK_UNLCK,1)
            else:
                import fcntl
                fcntl.flock(self.file.fileno(),fcntl.LOCK_UN)
            self.file.close()
